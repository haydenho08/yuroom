-- Stage 1 schema: timetable reference data + ingestion bookkeeping.
-- Query-specific indexes for the "is it free?" engine are added in Stage 2,
-- once we know the exact query shapes.

create table term (
    id         bigint generated by default as identity primary key,
    code       varchar(16) not null unique,
    start_date date        not null,
    end_date   date        not null,
    constraint term_dates_ck check (end_date >= start_date)
);

create table building (
    id     bigint generated by default as identity primary key,
    code   varchar(16)  not null unique,
    name   varchar(128),
    campus varchar(32)
);

create table room (
    id          bigint generated by default as identity primary key,
    building_id bigint      not null references building (id),
    number      varchar(16) not null,
    constraint room_building_number_uk unique (building_id, number)
);

-- Every distinct payload we have ever collected, byte-for-byte.
-- Lets us re-parse history after fixing a parser bug without re-fetching.
create table raw_snapshot (
    id             bigint generated by default as identity primary key,
    source         varchar(64)  not null,
    fetched_at     timestamptz  not null,
    content_sha256 varchar(64)  not null,
    content        bytea        not null,
    content_type   varchar(100),
    etag           varchar(256),
    last_modified  varchar(64),
    constraint raw_snapshot_source_sha_uk unique (source, content_sha256)
);

create table ingestion_run (
    id              bigint generated by default as identity primary key,
    source          varchar(64) not null,
    started_at      timestamptz not null,
    finished_at     timestamptz,
    status          varchar(16) not null,
    snapshot_id     bigint references raw_snapshot (id),
    meetings_parsed integer,
    rows_rejected   integer,
    message         text,
    constraint ingestion_run_status_ck
        check (status in ('RUNNING', 'SUCCESS', 'UNCHANGED', 'BLOCKED', 'FAILED'))
);

-- "When did this source last succeed?" is asked before every run.
create index ingestion_run_source_started_idx on ingestion_run (source, started_at desc);

-- Meetings are bulk-inserted; a sequence with increment 50 lets Hibernate
-- batch inserts (IDENTITY columns force one round trip per row).
create sequence meeting_id_seq increment by 50;

create table meeting (
    id           bigint primary key,
    term_id      bigint      not null references term (id),
    room_id      bigint      not null references room (id),
    snapshot_id  bigint references raw_snapshot (id),
    day_of_week  smallint    not null,
    start_time   time        not null,
    end_time     time        not null,
    start_date   date        not null,
    end_date     date        not null,
    course_code  varchar(32),
    section      varchar(16),
    meeting_type varchar(8),
    constraint meeting_day_ck   check (day_of_week between 1 and 7),   -- ISO: 1 = Monday
    constraint meeting_time_ck  check (end_time > start_time),
    constraint meeting_dates_ck check (end_date >= start_date)
);

-- Ingestion replaces a term's meetings with "delete where term_id = ?".
create index meeting_term_idx on meeting (term_id);
