-- Anonymous "this room is actually occupied" reports.
-- Deliberately stores NOTHING about the reporter: no IP, no hash, no user id, no location.
-- Rate limiting happens in memory with keys that are never persisted (see ReportRateLimiter).
create table occupancy_report (
    id         bigint generated by default as identity primary key,
    room_id    bigint      not null references room (id),
    created_at timestamptz not null,
    expires_at timestamptz not null,
    constraint occupancy_report_expiry_ck check (expires_at > created_at)
);

-- "Active reports for these rooms": where expires_at > now [and room_id in (...)].
-- expires_at first because the active set is tiny compared with history; room_id is included
-- so the per-room count is answered from the index.
create index occupancy_report_active_idx on occupancy_report (expires_at, room_id) include (created_at);
