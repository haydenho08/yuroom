import java.time.LocalTime;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Random;

/**
 * Generates a realistic-looking but entirely SYNTHETIC timetable for the public demo, so the demo
 * isn't a campus where every room is free all day. Seeded, so the output is reproducible.
 *
 * <p>Real building codes (so Near me works), invented rooms, times and "DEMO nnnn" courses.
 * Not York's timetable and not derived from it.
 *
 * <pre>java scripts/GenerateDemoTimetable.java &gt; data/sample/timetable-demo.csv</pre>
 * (Java 21 runs a single source file directly; no build needed.)
 */
public class GenerateDemoTimetable {

    record Term(String code, String start, String end, long seed) {
    }

    static final List<Term> TERMS = List.of(
            new Term("2026FA", "2026-09-09", "2026-12-08", 2026),
            new Term("2027WI", "2027-01-04", "2027-04-06", 2027));

    static final Map<String, List<String>> ROOMS = new LinkedHashMap<>();

    static {
        ROOMS.put("ACW", List.of("004", "006", "102", "109", "206", "302"));
        ROOMS.put("BC", List.of("215", "230", "305"));
        ROOMS.put("CB", List.of("115", "122", "129"));
        ROOMS.put("CLH", List.of("A", "B", "C", "D", "E", "F", "G", "H", "I", "J", "K", "L"));
        ROOMS.put("DB", List.of("0001", "0005", "0009", "1004", "1005"));
        ROOMS.put("FC", List.of("152", "163"));
        ROOMS.put("HNE", List.of("030", "035"));
        ROOMS.put("LAS", List.of("A", "B", "C", "1002", "1006", "2002"));
        ROOMS.put("LSB", List.of("103", "105", "106"));
        ROOMS.put("PSE", List.of("317", "321"));
        ROOMS.put("R", List.of("N102", "N203", "S137", "S201", "S203"));
        ROOMS.put("SC", List.of("214", "218"));
        ROOMS.put("SLH", List.of("A", "B", "C", "D", "E", "F"));
        ROOMS.put("VH", List.of("A", "B", "C", "D", "1152", "1154"));
        ROOMS.put("YH", List.of("A100", "B204"));
    }

    static final LocalTime FIRST = LocalTime.of(8, 30);
    static final LocalTime LAST_END = LocalTime.of(22, 0);
    static int course = 1000;

    public static void main(String[] args) {
        System.out.println("# SYNTHETIC demo timetable, generated by scripts/GenerateDemoTimetable.java. Not York's timetable.");
        System.out.println("# Building codes are real York buildings; rooms, courses and times are invented.");
        System.out.println("term_code,campus,building,room,day,start_time,end_time,duration_minutes,start_date,end_date,course_code,section,meeting_type");
        for (Term term : TERMS) {
            Random random = new Random(term.seed());
            ROOMS.forEach((building, rooms) -> {
                for (String room : rooms) {
                    double busy = 0.35 + random.nextDouble() * 0.5; // each room has its own popularity
                    for (String days : List.of("MW", "TR", "F")) {
                        fillDay(random, term, building, room, days, busy);
                    }
                }
            });
        }
    }

    /** Walks the day on a half-hour grid, placing classes with probability {@code busy}. */
    static void fillDay(Random random, Term term, String building, String room, String days, double busy) {
        LocalTime t = FIRST;
        while (true) {
            int minutes = switch (days) {
                case "MW", "TR" -> random.nextInt(5) == 0 ? 180 : (random.nextBoolean() ? 80 : 90);
                default -> List.of(60, 120, 180).get(random.nextInt(3));
            };
            LocalTime end = t.plusMinutes(minutes);
            if (end.isAfter(LAST_END) || end.isBefore(t)) {
                return;
            }
            boolean evening = !t.isBefore(LocalTime.of(17, 30));
            if (random.nextDouble() < (evening ? busy / 3 : busy)) {
                String type = minutes == 180 ? (evening ? "SEMR" : "LAB") : (random.nextInt(4) == 0 ? "TUTR" : "LECT");
                String campus = building.equals("YH") ? "Glendon" : "Keele";
                System.out.printf("%s,%s,%s,%s,%s,%s,,%d,%s,%s,DEMO %d,%s,%s%n", term.code(), campus, building, room, days,
                        t, minutes, term.start(), term.end(), course++, (char) ('A' + random.nextInt(3)), type);
                t = roundUpToHalfHour(end.plusMinutes(10));
            } else {
                t = t.plusMinutes(30L * (1 + random.nextInt(3)));
            }
        }
    }

    static LocalTime roundUpToHalfHour(LocalTime time) {
        int m = time.getHour() * 60 + time.getMinute();
        int rounded = (m + 29) / 30 * 30;
        return rounded >= 24 * 60 ? LocalTime.MAX : LocalTime.of(rounded / 60, rounded % 60);
    }
}
